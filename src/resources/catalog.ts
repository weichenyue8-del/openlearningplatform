export function getResourcesForLesson(courseSlug: string, lessonSlug: string) {
  return learningResources.filter((resource) =>
    resource.lessonRefs.some(
      (ref) => ref.courseSlug === courseSlug && ref.lessonSlug === lessonSlug,
    ),
  );
}
